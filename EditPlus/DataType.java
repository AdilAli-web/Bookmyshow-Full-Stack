class DataType 
{
	public static void main(String[] args) 
	{
		int age=20;
		int marks=99;
		int student=40;
		System.out.println("Age: "+age);
		System.out.println("marks: "+marks);
		System.out.println("student: "+student);

		System.out.println("------------------------Decimal---------------");

		//Decimal data type
		double price=99.88;
		float height=5.10f;
		double salary=3555232424245.34f;
		System.out.println("price: "+price);
		System.out.println("height: "+height);
		System.out.println("salary: "+salary);

		System.out.println("------------------------Char---------------");

		char grade='A';
		char sec='C';
		System.out.println("grade: "+grade);
		System.out.println("sec: "+sec);

		System.out.println("------------------------boolean---------------");
		
		boolean isPassed=true;
		boolean isPaymentDone=true;
		System.out.println("isPassed: "+isPassed);
		System.out.println("isPaymentDone: "+isPaymentDone);

		System.out.println("------------------------String---------------");
		
		String name="Rahul";
		String city="Agra";
		String course="Java";
		System.out.println("name: "+name);
		System.out.println("city: "+city);
		System.out.println("course: "+course);

		System.out.println("------------------------comparosion---------------");
			
		byte smallNum=100;
		short mediumNum=300;
		int normalNum=100000;
		long bigNum=8938397839837L;


		System.out.println("smallNum: "+smallNum);
		System.out.println("mediumNum: "+mediumNum);
		System.out.println("normalNum: "+normalNum);
		System.out.println("bigNum: "+bigNum);

	}
}
